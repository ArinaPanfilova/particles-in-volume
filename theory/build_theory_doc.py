fig_no = [0]


def para(*parts, align=None, size=None, color=None, after=None):
    """parts — строки; '**текст**' — жирным."""
    p = doc.add_paragraph()
    for part in parts:
        bold = part.startswith('**') and part.endswith('**')
        r = p.add_run(part[2:-2] if bold else part)
        r.bold = bold
        if size:
            r.font.size = Pt(size)
        if color:
            r.font.color.rgb = color
    if align:
        p.alignment = align
    if after is not None:
        p.paragraph_format.space_after = Pt(after)
    return p


def bullets(items, style='List Bullet'):
    for it in items:
        p = doc.add_paragraph(style=style)
        if isinstance(it, tuple):
            r = p.add_run(it[0])
            r.bold = True
            p.add_run(it[1])
        else:
            p.add_run(it)
        p.paragraph_format.space_after = Pt(3)


def caption(text):
    fig_no[0] += 1
    p = para('Рис. %d. ' % fig_no[0], text, align=WD_ALIGN_PARAGRAPH.CENTER, size=10,
             color=RGBColor(0x55, 0x5F, 0x6D), after=12)
    p.runs[0].bold = True


def figure(name, text, width=16.5):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.keep_with_next = True
    p.add_run().add_picture(str(IMG / (name + '.png')), width=Cm(width))
    caption(text)


def no_borders(table):
    tbl = table._tbl
    pr = tbl.tblPr
    b = OxmlElement('w:tblBorders')
    for edge in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        e = OxmlElement('w:' + edge)
        e.set(qn('w:val'), 'nil')
        b.append(e)
    pr.append(b)


def figure_pair(left, right, sub_left, sub_right, text, width=8.0):
    t = doc.add_table(rows=2, cols=2)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    no_borders(t)
    for col, (name, sub) in enumerate(((left, sub_left), (right, sub_right))):
        c = t.cell(0, col).paragraphs[0]
        c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        c.add_run().add_picture(str(IMG / (name + '.png')), width=Cm(width))
        s = t.cell(1, col).paragraphs[0]
        s.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = s.add_run(sub)
        r.font.size = Pt(10)
        r.italic = True
    caption(text)


def shade(cell, hex_fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hex_fill)
    tcPr.append(shd)


def table(rows, widths=(5.0, 12.0), header=None):
    t = doc.add_table(rows=0, cols=2)
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    if header:
        rows = [header] + list(rows)
    for i, (a, b) in enumerate(rows):
        cells = t.add_row().cells
        for c, txt, w in zip(cells, (a, b), widths):
            c.width = Cm(w)
            p = c.paragraphs[0]
            r = p.add_run(txt)
            r.font.size = Pt(11)
            if header and i == 0:
                r.bold = True
                shade(c, 'E6EBF2')
            elif c is cells[0]:
                r.bold = True
    doc.add_paragraph().paragraph_format.space_after = Pt(2)



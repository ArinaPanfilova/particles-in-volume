doc.add_heading('6. Как n меняется во времени: марковский процесс', level=1)
idea(['Одна молекула то входит в область, то выходит — «телеграфный сигнал». Между входами и выходами она много '
      'раз сталкивается и «забывает», где была. Значит, вероятность выйти за маленький промежуток времени dt не '
      'зависит от прошлого: она равна ', M(r'\gamma_- \,dt'), ', а войти — ', M(r'\gamma_+ \,dt'),
      '. Такой процесс без памяти называется ', '**марковским**', '.'])
step('Одна молекула')
eq(r'p = \frac{\gamma_+}{\gamma_+ + \gamma_-} = \frac{\langle t_1 \rangle}{\langle t_1 \rangle + \langle t_2 \rangle},')
para('где ', M(r'\langle t_1 \rangle = 1/\gamma_-'), ' — среднее время внутри, ', M(r'\langle t_2 \rangle = 1/\gamma_+'),
     ' — снаружи. Доля времени внутри — это и есть p.')
step('Все молекулы: кинетическое уравнение')
para('Если в области n молекул, то войти может любая из N − n наружных (скорость ', M(r'(N-n)\gamma_+'),
     '), выйти — любая из n внутренних (скорость ', M(r'n\gamma_-'), '). Вероятность ', M('P_n'),
     ' меняется как «приход минус уход»:')
eq(r'\frac{dP_n}{dt} = (N-n+1)\gamma_+ P_{n-1} + (n+1)\gamma_- P_{n+1} - \left[(N-n)\gamma_+ + n\gamma_-\right] P_n.')
para('Первые два слагаемых — переходы в состояние n из n − 1 и из n + 1, последнее — уход из n.')
step('Почему в равновесии получается бином')
para('В равновесии поток вверх между соседними состояниями равен потоку вниз (детальное равновесие):')
eq(r'P_n\,(N-n)\,\gamma_+ = P_{n+1}\,(n+1)\,\gamma_- \;\Rightarrow\; \frac{P_{n+1}}{P_n} = \frac{N-n}{n+1}\cdot\frac{\gamma_+}{\gamma_-}.')
para('Ровно такое отношение соседних членов у бинома с ', M(r'p = \gamma_+/(\gamma_+ + \gamma_-)'), '.')
step('Как система приходит к равновесию')
eq(r'\frac{d\langle n \rangle}{dt} = (N - \langle n \rangle)\gamma_+ - \langle n \rangle \gamma_- \;\Rightarrow\; \langle n \rangle(t) = Np + \left(n(0) - Np\right) e^{-t/\tau}, \qquad \frac{1}{\tau} = \gamma_+ + \gamma_-.')
para('Отклонение от равновесия уменьшается в e ≈ 2.7 раза за каждое время τ.')
figure_pair('hole_start', 'hole_end', 'в начале: все снаружи', 'через минуту', 'Заполнение области через отверстие.')
figure('hole_series', 'n(t) растёт и выходит на коридор ⟨n⟩ ± σ.', width=10)
step('Почему опыт на коротком прогоне не совпадает с теорией')
para('Соседние измерения n почти одинаковы: n меняется заметно только за время порядка τ. Поэтому независимых '
     'измерений гораздо меньше, чем «Число выборок»:')
eq(r'N_{\text{незав}} \approx \frac{T_{\text{наблюдения}}}{2\tau}, \qquad \text{ошибка среднего} \approx \frac{\sigma}{\sqrt{N_{\text{незав}}}}.')
para('Ответ на вопрос «почему не совпадает»: «дайте поработать дольше» — и показать, как числа сближаются.')
figure('charts_rotated', 'Кнопка «⟳ 90°»: гистограмма рядом с n(t) на одной шкале.')
demo(['«Моделирование → Начальное состояние → все снаружи объёма» или опыт «Заполнение области через отверстие»: '
      'n(t) экспоненциально выходит на Np. Кнопка «⟳ 90°»: гистограмма показывает, сколько времени n(t) провело '
      'на каждом уровне (эргодичность: среднее по времени = среднее по ансамблю).'])


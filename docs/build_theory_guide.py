step('Формула')
eq(r'P(n) \approx \frac{1}{\sqrt{2\pi\sigma^2}}\,\exp\!\left(-\frac{(n-Np)^2}{2\sigma^2}\right), \qquad \sigma^2 = Np(1-p).')
para('Правило: в пределах ', M(r'\pm\sigma'), ' от среднего — около 68 % времени, в пределах ', M(r'\pm 2\sigma'),
     ' — около 95 %.')
step('Когда можно')
para('Число n — целое, а кривая Гаусса — непрерывная «плотность» ', M('f(x)'), '. Вероятность целого n — это '
     'площадь под кривой над отрезком шириной 1:')
eq(r'P(n) = \int_{n-1/2}^{n+1/2} f(x)\,dx \approx f(n).')
para('Приближение хорошее, если кривая почти не меняется на ширине одной клетки, то есть ', M(r'\sigma \gg 1'),
     '. Важна именно ширина распределения, а не величина n: в задаче 3.3 ', M('n'), ' велико, но ',
     M(r'\sigma^2 = Np(1-p)'), ' мала, и Гаусс не работает.')
step('Пример')
para('«Несколько молекул»: ', M('N = 6'), ', ', M(r'\sigma \approx 1'), ' — кривая заметно расходится со '
     'столбиками. «Область в углу»: ', M('N = 60'), ', ', M(r'\sigma \approx 3'), ' — совпадает хорошо.')
figure('hist_sigma', 'Раскраска «по σ»: зелёные — в пределах ±σ, жёлтые — до ±2σ, красные — дальше.', width=10)
demo(['Галочка «Гаусс» под гистограммой. Меню «Вид → Гистограмма → по отклонению от ⟨n⟩» показывает правило '
      '68–95 % цветом.'])


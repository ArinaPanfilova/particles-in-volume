def omath(tex):
    """LaTeX -> формула Word (элемент m:oMath). Отступы quad при переводе теряются, ставим широкие пробелы."""
    tex = tex.replace(r'\qquad', r'\text{  }').replace(r'\quad', r'\text{ }')
    return XSL(etree.fromstring(convert(tex).encode())).getroot()


def fill(p, parts, size=None):
    """parts: строки ('**…**' — жирным) и ('m', latex) — формула в строке."""
    for part in parts:
        if isinstance(part, tuple):
            p._p.append(omath(part[1]))
            continue
        for k, piece in enumerate(re.split(r'\*\*(.+?)\*\*', part)):  # **…** внутри строки — жирным
            if not piece:
                continue
            r = p.add_run(piece)
            r.bold = k % 2 == 1
            if size:
                r.font.size = Pt(size)
    return p


def para(*parts, after=None, container=None):
    p = (container or doc).add_paragraph()
    fill(p, parts)
    if after is not None:
        p.paragraph_format.space_after = Pt(after)
    return p


def eq(tex, container=None):
    p = (container or doc).add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(8)
    mp = OxmlElement('m:oMathPara')
    mp.append(omath(tex))
    p._p.append(mp)
    return p


def bullets(items, container=None):
    for it in items:
        p = (container or doc).add_paragraph(style='List Bullet')
        fill(p, it if isinstance(it, (list, tuple)) and not (len(it) == 2 and it[0] == 'm') else [it])
        p.paragraph_format.space_after = Pt(3)


def shade(cell, fill_hex):
    pr = cell._tc.get_or_add_tcPr()
    s = OxmlElement('w:shd')
    s.set(qn('w:val'), 'clear')
    s.set(qn('w:color'), 'auto')
    s.set(qn('w:fill'), fill_hex)
    pr.append(s)


def box(label, color, *paras):
    """Цветная плашка: «Идея», «В программе». paras — списки частей абзацев."""
    t = doc.add_table(rows=1, cols=1)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    c = t.cell(0, 0)
    c.width = Cm(17)
    shade(c, color)
    first = c.paragraphs[0]
    r = first.add_run(label + '. ')
    r.bold = True
    r.font.color.rgb = ACCENT
    fill(first, paras[0])
    for parts in paras[1:]:
        fill(c.add_paragraph(), parts)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)


